def run_tests(folder: Path) -> int:
    return subprocess.run([sys.executable, "-m", "unittest", "discover", "-s", "tests", "-t", "."], cwd=folder,
                          capture_output=True, text=True).returncode


# What a scratch copy leaves out. evidence/ stays in: the documents name its files and a test reads one (until
# 2026-10-14 it was left out, so those tests failed in every copy and every mutation looked caught).
COPY_IGNORE = (".venv*", "__pycache__", ".git")


def _copy(dest: Path) -> None:
    shutil.copytree(ROOT, dest, ignore=shutil.ignore_patterns(*COPY_IGNORE))


def copy_passes() -> bool:
    """The unmutated suite must pass in a scratch copy made exactly like a mutation's; otherwise a failure caused by
    the copy itself would make every mutation look caught."""
    with tempfile.TemporaryDirectory() as tmp:
        copy = Path(tmp) / "engine"
        _copy(copy)
        return run_tests(copy) == 0


def _one(relative: str, source: str, old: str, new: str) -> bool:
    """Apply one mutation to its own scratch copy of the engine and run the whole suite there."""
    with tempfile.TemporaryDirectory() as tmp:
        copy = Path(tmp) / "engine"
        _copy(copy)
        (copy / relative).write_text(source.replace(old, new), encoding="utf-8")
        return run_tests(copy) != 0


def main(argv=None) -> int:
    import argparse
    from concurrent.futures import ThreadPoolExecutor
    parser = argparse.ArgumentParser(description="CareerOS mutation check")
    parser.add_argument("--workers", type=int, default=1, help="mutations tested in parallel (each in its own copy)")
    args = parser.parse_args(argv)
    if run_tests(ROOT) != 0:
        print("baseline tests fail; fix them before running mutations")
        return 2
    if not copy_passes():
        print("the unmutated suite fails in a scratch copy; fix the copy before running mutations")
        return 2
    results, sources, jobs = [None] * len(MUTATIONS), {}, []
    for index, (relative, old, new, label) in enumerate(MUTATIONS):
        source = (ROOT / relative).read_text(encoding="utf-8")
        sources[relative] = hashlib.sha256(source.encode("utf-8")).hexdigest()
        if source.count(old) != 1:
            results[index] = {"mutation": label, "file": relative, "result": "ANCHOR_NOT_FOUND"}
            continue
        jobs.append((index, relative, source, old, new, label))

    def run(job):
        index, relative, source, old, new, label = job
        caught = _one(relative, source, old, new)
        print(f"{'CAUGHT  ' if caught else 'SURVIVED'}  {label}", flush=True)
        return index, {"mutation": label, "file": relative, "result": "CAUGHT" if caught else "SURVIVED"}

    with ThreadPoolExecutor(max_workers=max(1, args.workers)) as pool:
        for index, result in pool.map(run, jobs):
            results[index] = result
    caught = sum(r["result"] == "CAUGHT" for r in results)
    receipt = {"at": datetime.now(timezone.utc).isoformat(timespec="seconds"), "caught": caught, "total": len(results),
               "results": results, "source_sha256": sources}
    (ROOT / "evidence").mkdir(exist_ok=True)
    (ROOT / "evidence" / "mutation-receipt.json").write_text(json.dumps(receipt, indent=1), encoding="utf-8")
    print(f"\n{caught}/{len(results)} mutations caught")
    return 0 if caught == len(results) else 1


if __name__ == "__main__":
    sys.exit(main())
